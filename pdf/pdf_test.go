func TestGeneratePDF(t *testing.T) {
	doc, err := New(
		WithHeader("goframe report"),
		WithFooter("generated by goframe"),
		WithMetadata("Report", "tester", "unit test"),
	)
	if err != nil {
		t.Fatalf("New: %v", err)
	}

	if err := doc.Title("Monthly Report"); err != nil {
		t.Fatalf("Title: %v", err)
	}
	if err := doc.Heading("Summary"); err != nil {
		t.Fatalf("Heading: %v", err)
	}
	if err := doc.Paragraph("This is a long paragraph used to verify automatic line wrapping in the PDF document. " +
		"It should span multiple lines without exceeding the content width."); err != nil {
		t.Fatalf("Paragraph: %v", err)
	}
	if err := doc.Table(Table{
		Headers: []string{"Name", "Value", "Status"},
		Rows: [][]string{
			{"alpha", "10", "ok"},
			{"beta", "20", "disabled"},
			{"gamma", "30", "ok"},
		},
		Widths: []float64{2, 1, 1},
		Align:  []string{"left", "right", "center"},
		Zebra:  true,
	}); err != nil {
		t.Fatalf("Table: %v", err)
	}

	doc.PageBreak()
	if err := doc.Heading("Details"); err != nil {
		t.Fatalf("Heading 2: %v", err)
	}
	if err := doc.Paragraph("Second page content."); err != nil {
		t.Fatalf("Paragraph 2: %v", err)
	}

	data, err := doc.Bytes()
	if err != nil {
		t.Fatalf("Bytes: %v", err)
	}
	if !bytes.HasPrefix(data, []byte("%PDF-")) {
		t.Fatalf("unexpected pdf header: %q", string(data[:8]))
	}
	if len(data) < 1000 {
		t.Fatalf("pdf too small: %d", len(data))
	}
	if doc.Pages() < 2 {
		t.Fatalf("pages = %d, want >= 2", doc.Pages())
	}
	if err := doc.Paragraph("too late"); err != ErrClosed {
		t.Fatalf("append after finalize = %v, want ErrClosed", err)
	}
}

func TestTableSplitsPages(t *testing.T) {
	doc, err := New()
	if err != nil {
		t.Fatalf("New: %v", err)
	}
	rows := make([][]string, 80)
	for i := range rows {
		rows[i] = []string{"row", "some longer value to force wrapping in the table cell", "ok"}
	}
	if err := doc.Table(Table{
		Headers: []string{"A", "B", "C"},
		Rows:    rows,
		Widths:  []float64{1, 3, 1},
		Zebra:   true,
	}); err != nil {
		t.Fatalf("Table: %v", err)
	}
	if doc.Pages() < 2 {
		t.Fatalf("pages = %d, want >= 2", doc.Pages())
	}
	if _, err := doc.Bytes(); err != nil {
		t.Fatalf("Bytes: %v", err)
	}
}

